public class Variable {
    public static void main(String[] args)
    {
        int num1 = 5;
        int num2 = 3;

        System.out.println(num1);
        System.out.println(num2);

        System.out.println(num1 + " " + num2);

        System.out.printf("num1 = %d, num2 = %d\n", num1, num2);
    }
}
